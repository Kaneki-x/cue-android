package io.cueapp.android.icons;

import android.content.Context;
import android.content.res.AssetManager;
import android.util.Log;

import androidx.annotation.Nullable;

import io.cueapp.android.R;
import io.cueapp.android.util.IOUtils;

import net.lingala.zip4j.ZipFile;
import net.lingala.zip4j.io.inputstream.ZipInputStream;
import net.lingala.zip4j.model.FileHeader;

import org.json.JSONException;

import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.UUID;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.stream.Collectors;

public class IconPackManager {
    private static final String TAG = IconPackManager.class.getSimpleName();
    private static final String _packDefFilename = "pack.json";
    private static final String _bundledAssetsDir = "iconpacks";

    private File _iconsBaseDir;
    private List<IconPack> _iconPacks;
    // UUIDs of the bundled packs, most preferred first (generated by design/generate.py)
    private final List<String> _bundledOrder;
    // UUIDs of packs earlier versions bundled, whose bundled copies are removed
    private final List<String> _retired;

    public IconPackManager(Context context) {
        _bundledOrder = Arrays.asList(context.getResources().getStringArray(R.array.bundled_icon_packs));
        _retired = Arrays.asList(context.getResources().getStringArray(R.array.retired_icon_packs));
        // the bundled packs are installed on a background thread while the UI reads the list
        _iconPacks = new CopyOnWriteArrayList<>();
        _iconsBaseDir = new File(context.getFilesDir(), "icons");
        rescanIconPacks();
    }

    private IconPack getIconPackByUUID(UUID uuid) {
        List<IconPack> packs = _iconPacks.stream().filter(i -> i.getUUID().equals(uuid)).collect(Collectors.toList());
        if (packs.size() == 0) {
            return null;
        }

        return packs.get(0);
    }

    public boolean hasIconPack() {
        return _iconPacks.size() > 0;
    }

    /**
     * Returns the icon packs in the order the pickers offer them: the bundled packs in their
     * preferred order, then the others by name. The first one is the default.
     */
    public List<IconPack> getIconPacks() {
        List<IconPack> packs = new ArrayList<>(_iconPacks);
        packs.sort(Comparator.comparingInt((IconPack pack) -> {
            int index = _bundledOrder.indexOf(pack.getUUID().toString());
            return index == -1 ? Integer.MAX_VALUE : index;
        }).thenComparing(IconPack::getName));
        return packs;
    }

    public void removeIconPack(IconPack pack) throws IconPackException {
        try {
            File dir = getIconPackDir(pack);
            deleteDir(dir);
        } catch (IOException e) {
            throw new IconPackException(e);
        }

        _iconPacks.remove(pack);
    }

    public IconPack importPack(File inFile) throws IconPackException {
        try {
            // read and parse the icon pack definition file of the icon pack
            ZipFile zipFile = new ZipFile(inFile);
            FileHeader packHeader = zipFile.getFileHeader(_packDefFilename);
            if (packHeader == null) {
                throw new IOException("Unable to find pack.json in the root of the ZIP file");
            }
            IconPack pack;
            byte[] defBytes;
            try (ZipInputStream inStream = zipFile.getInputStream(packHeader)) {
                defBytes = IOUtils.readAll(inStream);
                pack = IconPack.fromBytes(defBytes);
            }

            // create a new directory to store the icon pack, based on the UUID and version
            File packDir = getIconPackDir(pack);
            if (!packDir.getCanonicalPath().startsWith(_iconsBaseDir.getCanonicalPath() + File.separator)) {
                throw new IOException("Attempted to write outside of the parent directory");
            }
            if (packDir.exists()) {
                throw new IconPackExistsException(pack);
            }
            IconPack existingPack = getIconPackByUUID(pack.getUUID());
            if (existingPack != null) {
                throw new IconPackExistsException(existingPack);
            }
            if (!packDir.exists() && !packDir.mkdirs()) {
                throw new IOException(String.format("Unable to create directories: %s", packDir.toString()));
            }

            // extract each of the defined icons to the icon pack directory
            for (IconPack.Icon icon : pack.getIcons()) {
                File destFile = new File(packDir, icon.getRelativeFilename());
                if (!destFile.getCanonicalPath().startsWith(packDir.getCanonicalPath() + File.separator)) {
                    throw new IOException("Attempted to write outside of the icon pack directory");
                }
                FileHeader iconHeader = zipFile.getFileHeader(icon.getRelativeFilename());
                if (iconHeader == null) {
                    throw new IOException(String.format("Unable to find %s relative to the root of the ZIP file", icon.getRelativeFilename()));
                }

                // create new directories for this file if needed
                File parent = destFile.getParentFile();
                if (parent != null && !parent.exists() && !parent.mkdirs()) {
                    throw new IOException(String.format("Unable to create directories: %s", packDir.toString()));
                }

                try (ZipInputStream inStream = zipFile.getInputStream(iconHeader);
                     FileOutputStream outStream = new FileOutputStream(destFile)) {
                    IOUtils.copy(inStream, outStream);
                }

                // after successful copy of the icon, store the new filename
                icon.setFile(destFile);
            }

            // write the icon pack definition file to the newly created directory
            try (FileOutputStream outStream = new FileOutputStream(new File(packDir, _packDefFilename))) {
                outStream.write(defBytes);
            }

            // after successful extraction of the icon pack, store the new directory
            pack.setDirectory(packDir);
            _iconPacks.add(pack);
            return pack;
        } catch (IOException | JSONException e) {
            throw new IconPackException(e);
        }
    }

    /**
     * Installs the icon packs that ship in the APK (assets/iconpacks), each version once. A pack
     * the user removed stays removed, and one they imported in the same or a newer version is
     * kept. The record of what was installed lives next to the packs, in a directory that is
     * not backed up, so a restore onto a new device installs them again.
     */
    public void installBundledPacks(Context context) {
        removeRetiredPacks();
        AssetManager assets = context.getAssets();
        String[] names;
        try {
            names = assets.list(_bundledAssetsDir);
        } catch (IOException e) {
            Log.e(TAG, "Unable to list the bundled icon packs", e);
            return;
        }
        if (names == null) {
            return;
        }

        for (String name : names) {
            File tempFile = null;
            try {
                tempFile = File.createTempFile("icon-pack-", "", context.getCacheDir());
                try (InputStream inStream = assets.open(_bundledAssetsDir + "/" + name);
                     FileOutputStream outStream = new FileOutputStream(tempFile)) {
                    IOUtils.copy(inStream, outStream);
                }

                IconPack bundled;
                try (ZipFile zipFile = new ZipFile(tempFile)) {
                    FileHeader packHeader = zipFile.getFileHeader(_packDefFilename);
                    if (packHeader == null) {
                        throw new IOException("Unable to find pack.json in the root of " + name);
                    }
                    try (ZipInputStream inStream = zipFile.getInputStream(packHeader)) {
                        bundled = IconPack.fromBytes(IOUtils.readAll(inStream));
                    }
                }

                File marker = new File(_iconsBaseDir, bundled.getUUID() + ".bundled");
                int handled = readBundledMarker(marker);
                if (handled >= bundled.getVersion()) {
                    continue;
                }

                IconPack existing = getIconPackByUUID(bundled.getUUID());
                if ((existing == null && handled == -1) || (existing != null && existing.getVersion() < bundled.getVersion())) {
                    if (existing != null) {
                        removeIconPack(existing);
                    } else {
                        // left by an extraction that was interrupted
                        File stale = new File(_iconsBaseDir, bundled.getUUID().toString());
                        if (stale.exists()) {
                            deleteDir(stale);
                        }
                    }
                    importPack(tempFile);
                }
                writeBundledMarker(marker, bundled.getVersion());
            } catch (IOException | JSONException | IconPackException e) {
                Log.e(TAG, String.format("Unable to install the bundled icon pack %s", name), e);
            } finally {
                if (tempFile != null) {
                    tempFile.delete();
                }
            }
        }
    }

    /**
     * Removes the packs earlier versions bundled (the four Aegis packs, now merged into one) where
     * the app installed them itself: their marker holds that version or a later one. A newer copy
     * the user imported stays. The same rule as the iOS app.
     */
    private void removeRetiredPacks() {
        for (String uuid : _retired) {
            File marker = new File(_iconsBaseDir, uuid + ".bundled");
            int handled = readBundledMarker(marker);
            if (handled == -1) {
                continue;
            }
            IconPack existing = getIconPackByUUID(UUID.fromString(uuid));
            try {
                if (existing != null) {
                    if (existing.getVersion() > handled) {
                        continue;
                    }
                    removeIconPack(existing);
                }
                File dir = new File(_iconsBaseDir, uuid);
                if (dir.exists()) {
                    deleteDir(dir);
                }
                if (!marker.delete()) {
                    Log.w(TAG, String.format("Unable to delete %s", marker));
                }
            } catch (IconPackException | IOException e) {
                Log.e(TAG, String.format("Unable to remove the retired icon pack %s", uuid), e);
            }
        }
    }

    private static int readBundledMarker(File marker) {
        if (!marker.exists()) {
            return -1;
        }
        try (FileInputStream inStream = new FileInputStream(marker)) {
            return Integer.parseInt(new String(IOUtils.readAll(inStream), StandardCharsets.UTF_8).trim());
        } catch (IOException | NumberFormatException e) {
            return -1;
        }
    }

    private void writeBundledMarker(File marker, int version) throws IOException {
        if (!_iconsBaseDir.exists() && !_iconsBaseDir.mkdirs()) {
            throw new IOException(String.format("Unable to create directories: %s", _iconsBaseDir));
        }
        try (FileOutputStream outStream = new FileOutputStream(marker)) {
            outStream.write(Integer.toString(version).getBytes(StandardCharsets.UTF_8));
        }
    }

    /**
     * The icon a new entry or 分配图标 takes for the issuer: the first suggestion of the first
     * pack, in getIconPacks() order, that has one (the iOS app picks the same way).
     */
    @Nullable
    public IconPack.Icon getSuggestedIcon(String issuer) {
        for (IconPack pack : getIconPacks()) {
            List<IconPack.Icon> icons = pack.getSuggestedIcons(issuer);
            if (!icons.isEmpty()) {
                return icons.get(0);
            }
        }
        return null;
    }

    private void rescanIconPacks() {
        _iconPacks.clear();

        File[] dirs = _iconsBaseDir.listFiles();
        if (dirs == null) {
            return;
        }

        for (File dir : dirs) {
            if (!dir.isDirectory()) {
                 continue;
            }

            UUID uuid;
            try {
                uuid = UUID.fromString(dir.getName());
            } catch (IllegalArgumentException e) {
                e.printStackTrace();
                continue;
            }

            File versionDir = getLatestVersionDir(dir);
            if (versionDir != null) {
                IconPack pack;
                try (FileInputStream inStream = new FileInputStream(new File(versionDir, _packDefFilename))) {
                    byte[] bytes = IOUtils.readAll(inStream);
                    pack = IconPack.fromBytes(bytes);
                    pack.setDirectory(versionDir);
                } catch (JSONException | IOException e) {
                    e.printStackTrace();
                    continue;
                }

                for (IconPack.Icon icon : pack.getIcons()) {
                    icon.setFile(new File(versionDir, icon.getRelativeFilename()));
                }

                // do a sanity check on the UUID and version
                if (pack.getUUID().equals(uuid) && pack.getVersion() == Integer.parseInt(versionDir.getName())) {
                    _iconPacks.add(pack);
                }
            }
        }
    }

    private File getIconPackDir(IconPack pack) {
        return new File(_iconsBaseDir, pack.getUUID() + File.separator + pack.getVersion());
    }

    @Nullable
    private static File getLatestVersionDir(File packDir) {
        File[] dirs = packDir.listFiles();
        if (dirs == null) {
            return null;
        }

        int latestVersion = -1;
        for (File versionDir : dirs) {
            int version;
            try {
                version = Integer.parseInt(versionDir.getName());
            } catch (NumberFormatException ignored) {
                continue;
            }

            if (latestVersion == -1 || version > latestVersion) {
                latestVersion = version;
            }
        }

        if (latestVersion == -1) {
            return null;
        }

        return new File(packDir, Integer.toString(latestVersion));
    }

    private static void deleteDir(File dir) throws IOException {
        if (dir.isDirectory()) {
            File[] children = dir.listFiles();
            if (children != null) {
                for (File child : children) {
                    deleteDir(child);
                }
            }
        }

        if (!dir.delete()) {
            throw new IOException(String.format("Unable to delete directory: %s", dir));
        }
    }
}
